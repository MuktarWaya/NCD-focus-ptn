import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const source=await fs.readFile(path.join(root,'backend/gas_backend.js'),'utf8');
const names=['validateNcdReportData_','validateTrackingData_','trackingRoundOrder_','computeDashboardStats_','pingpongGlucoseScore_','pingpongBpScore_','pingpongIsPatient_','pingpongClassify_','buildDailyNotificationSummaryFromData_','isUrgentQuarterlyLog_','toNotificationTarget_','getLatestQuarterlyLog_','getImportantTargetChanges_','buildRecordEventTelegramMessage_','parseDate','getTodayThaiDate'];
const variables=['ACTIVE_VILLAGES','TRACKING_ROUNDS','PINGPONG_LABELS_','PINGPONG_RANK_'];
const selected=variables.map(name=>{const line=source.split(/\r?\n/).find(l=>l.startsWith('var '+name+' ='));if(!line)throw Error('Missing variable '+name);return line;});
for(const name of names){
  const match=source.match(new RegExp('^function '+name+'\\([^]*?^\\}', 'm'));
  if(!match)throw Error('Missing pure rule '+name);
  selected.push(match[0]);
}
// Generated from unchanged legacy functions; parity is tested against original source.
const rules=selected.join('\n\n').replace(/var mockWorkers = \[[\s\S]*?\n  \];/,'var mockWorkers = [];').split('\n').map(line=>line.trimEnd()).join('\n');
await fs.writeFile(path.join(root,'cloudflare/src/rules.mjs'),'// Generated by scripts/generate-rules.mjs from backend/gas_backend.js.\n'+rules+'\nexport { '+names.join(', ')+' };\n');
console.log('Generated '+names.length+' legacy pure rules');
